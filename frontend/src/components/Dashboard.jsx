import React, { useEffect, useState } from 'react';
import { io } from 'socket.io-client';

const BACKEND_URL = "http://localhost:5000";

// Inside the main Dashboard Component:
const [metricsData, setMetricsData] = useState([]);
const [consoleLogs, setConsoleLogs] = useState([]);
const [activeTenant, setActiveTenant] = useState("64ad5c4465b556525274404b8"); // Matching the token on screen

useEffect(() => {
    if (!activeTenant) return;

    // 1. Establish the Live WebSocket Pipe for the Diagnostics Console
    const socket = io(BACKEND_URL);

    socket.emit('join-tenant-room', activeTenant);
    setConsoleLogs(prev => [...prev, `[SOCKET]: Encrypted channel linked for Tenant Space.`]);

    // Intercept the logs coming straight out of your BullMQ Worker
    socket.on('deployment-log', (data) => {
        setConsoleLogs(prev => [...prev, data.logLine]);
    });

    // 2. Poll the real-time database numbers generated by your backend Mock Engine
    const fetchLiveTelemetry = async () => {
        try {
            const response = await fetch(`${BACKEND_URL}/api/metrics`, {
                headers: { 'x-tenant-id': activeTenant }
            });
            if (response.ok) {
                const rawData = await response.json();
                // Map backend timestamp logs to the frontend AreaChart data array format
                setMetricsData(rawData.map(item => ({
                    name: new Date(item.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
                    AWS: item.metricType === 'CostPerHour' && item.resourceName.includes('aws') ? item.value : undefined,
                    Azure: item.metricType === 'CostPerHour' && item.resourceName.includes('azure') ? item.value : undefined,
                })).filter(e => e.AWS || e.Azure));
            }
        } catch (err) {
            console.error("API Sync Error:", err);
        }
    };

    fetchLiveTelemetry();
    const pollTimer = setInterval(fetchLiveTelemetry, 10000); // Fetch new numbers every 10 seconds

    return () => {
        socket.disconnect();
        clearInterval(pollTimer);
    };
}, [activeTenant]);
